/*
Question 8: Variable Reassignment
Task: Create an int variable score = 50. Print it. Then reassign score to 100 and print it again.

Expected Output:

Initial Score: 50
Updated Score: 100
*/
package Basics;
public class Basics08 {
    public static void main(String[] args) {
        int score = 50;
        System.out.println("Initial Score: " + score);
        score = 100;
        System.out.println("Updated Score: " + score);
    }
}
