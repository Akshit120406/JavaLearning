package Basics;
public class Basics04 {
    public static void main(String[] args) {
        int a = 15;
        int b = 5;
        System.out.println("Sum: " + (a + b));
        System.out.println("Diffrence: " + (a - b));
        System.out.println("Product: " + (a * b));
    }
}
