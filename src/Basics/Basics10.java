/*
Question 10: Simple Area Calculator
Task: Create two double variables length = 8.5 and width = 4.0. Calculate the area of a rectangle (length * width) and print the result.

Expected Output:

Area of Rectangle: 34.0
*/
package Basics;
public class Basics10 {
    public static void main(String[] args) {
        double length = 8.5;
        double width = 4.0;
        double area = length * width;
        System.out.println("Area of Rectangle: " + area);
    }
}